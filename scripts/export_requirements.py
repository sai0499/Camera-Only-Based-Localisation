"""Export the lock, retaining explicit Windows CUDA wheel sources."""
import os
from pathlib import Path
import re
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def render(raw, lock):
    for name in ("torch", "torchvision"):
        package = next(p for p in lock["package"] if p["name"] == name)
        wheel = next(w for w in package["wheels"] if w["url"].endswith("cp312-cp312-win_amd64.whl"))
        pattern = rf"(?m)^{name}==[^\n]*(?:\n[ \t]+--hash[^\n]*)*"
        match = re.search(pattern, raw)
        if match is None:
            raise ValueError(f"Missing locked requirement: {name}")
        first = match.group().splitlines()[0].removesuffix("\\").rstrip()
        marker = " ;" + first.split(" ;", 1)[1] if " ;" in first else ""
        replacement = f"{name} @ {wheel['url']}{marker} \\\n    --hash={wheel['hash']}"
        raw = raw[:match.start()] + replacement + raw[match.end():]
    return "# Generated by scripts/export_requirements.py; prefer setup.cmd / uv sync --locked.\n" + raw


def main():
    env = dict(os.environ, UV_CACHE_DIR=str(ROOT / ".setup/cache"),
               UV_PYTHON_INSTALL_DIR=str(ROOT / ".setup/python"))
    result = subprocess.run([str(ROOT / ".setup/uv/uv.exe"), "export", "--frozen", "--offline",
                             "--no-emit-project", "--no-header"], cwd=ROOT, env=env,
                            capture_output=True, text=True, encoding="utf-8", check=True)
    lock = tomllib.loads((ROOT / "uv.lock").read_text(encoding="utf-8"))
    (ROOT / "requirements.txt").write_text(render(result.stdout, lock), encoding="utf-8")


if __name__ == "__main__":
    main()
